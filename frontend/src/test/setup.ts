import '@testing-library/jest-dom/vitest'
import { cleanup } from '@testing-library/react'
import { afterEach } from 'vitest'

afterEach(() => {
  cleanup()
})

// jsdom does not implement matchMedia; the responsive sidebar hook needs it.
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
})

// jsdom does not implement scrollIntoView (used by focus management).
Element.prototype.scrollIntoView ??= () => {}

// jsdom does not implement ResizeObserver; Recharts ResponsiveContainer needs it.
if (typeof globalThis.ResizeObserver === 'undefined') {
  globalThis.ResizeObserver = class {
    observe() {}
    unobserve() {}
    disconnect() {}
  } as unknown as typeof ResizeObserver
}

// jsdom does not implement createObjectURL (used by the prototype CSV export).
if (typeof URL.createObjectURL === 'undefined') {
  URL.createObjectURL = () => 'blob:demo'
  URL.revokeObjectURL = () => {}
}
